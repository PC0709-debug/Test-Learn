// tools/build-cards.js — turns verified fact batches into the game's deck.
//
// Big picture: card writing and fact-checking happen in content/work/:
//   <batch>.draft.json    cards written from sources
//   <batch>.check.json    independent checker's scores for each card
//   <batch>.repair.json   rewrites of cards that failed (if any)
//   <batch>.recheck.json  independent scores for the rewrites
// This script keeps ONLY cards that scored 90+ with no hard fail, then writes:
//   js/cards-data.js                 what the game loads
//   content/verification-report.md  the audit trail, one line per card
//
// Run: node tools/build-cards.js

const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const WORK = path.join(ROOT, 'content/work');
const PASS = 90;

// Strict audit: cards that passed 90+ but whose checker noted a doubt
// (a quote it could not see, or an extra claim with only one source).
// The user's bar is "confirmed", so these are cut too.
const EXCLUDE = {
  'floor-03-01': 'checker could not see the quoted BLS sentence',
  'floor-04-04': 'explain wording not surfaced in fetched excerpt',
  'obs-03-26': 'explain details each single-sourced',
  'sectors-02-14': 'dollar figure in explain single-sourced',
  'vault-03-14': 'one quote not confirmed verbatim',
  'philo-03-03': 'date in explain rests on one source',
};

const read = f => { try { return JSON.parse(fs.readFileSync(path.join(WORK, f), 'utf8')); } catch { return null; } };
const passes = s => s && s.pass === true && !s.hardFail && Number(s.total) >= PASS;

const batches = [...new Set(fs.readdirSync(WORK).filter(f => f.endsWith('.draft.json')).map(f => f.replace('.draft.json', '')))].sort();
const kept = [], dropped = [], report = [];
const seenQ = new Set();

for (const b of batches) {
  const draft = read(`${b}.draft.json`) || [];
  const check = Object.fromEntries((read(`${b}.check.json`) || []).map(s => [s.id, s]));
  const repair = Object.fromEntries((read(`${b}.repair.json`) || []).map(c => [c.id, c]));
  const recheck = Object.fromEntries((read(`${b}.recheck.json`) || []).map(s => [s.id, s]));

  for (const card of draft) {
    let final = null, score = check[card.id], stage = 'check';
    if (passes(score)) final = card;
    else if (repair[card.id] && passes(recheck[card.id])) { final = repair[card.id]; score = recheck[card.id]; stage = 'repaired'; }

    const key = (final || card).q.trim().toLowerCase();
    if (final && EXCLUDE[card.id]) { dropped.push({ id: card.id, why: 'audit: ' + EXCLUDE[card.id] }); continue; }
    if (final && seenQ.has(key)) { dropped.push({ id: card.id, why: 'duplicate question' }); continue; }
    if (final) {
      seenQ.add(key);
      final.score = Number(score.total);
      kept.push(final);
      report.push(`| ${final.id} | ${final.score} | ${stage} | ${final.q.replace(/\|/g, '/')} | ${final.a.replace(/\|/g, '/')} | ${(final.sources || []).map(s => `[src](${s.url})`).join(' ')} |`);
    } else {
      const s = recheck[card.id] || check[card.id] || {};
      dropped.push({ id: card.id, why: s.hardFail || s.issue || 'not scored' });
    }
  }
}

const header = `// AUTO-GENERATED by tools/build-cards.js — do not edit by hand.\n// Source quotes live in content/work and the verification report; only links ship here.\n// ${kept.length} cards, each source-traced and independently scored ${PASS}+/100.\n`;
fs.writeFileSync(path.join(ROOT, 'js/cards-data.js'), `${header}window.TICKER_CARDS = ${JSON.stringify(kept.map(c => ({ ...c, sources: (c.sources || []).map(({ url, title }) => ({ url, title })) })))};\n`);

const byDeck = kept.reduce((m, c) => (m[c.deck] = (m[c.deck] || 0) + 1, m), {});
fs.writeFileSync(path.join(ROOT, 'content/verification-report.md'),
`# Verification report

${kept.length} cards passed (score ${PASS}+ and no hard fail). ${dropped.length} were cut.

**By room:** ${Object.entries(byDeck).map(([d, n]) => `${d} ${n}`).join(' · ')}

## How each card was checked
1. **Written from a source:** the writer opened an authoritative page first, wrote the card from it, and saved a verbatim quote. Numbers, dates and named people need two independent sources.
2. **Independent check:** a separate agent opened every cited page and scored the card:
   source trace /30 · exact match /30 · one right answer /15 · still true /15 · precision /10.
3. **Hard fails** (cut whatever the score): mismatched number, date or name; quote not on the page; disputed fact; a decoy answer that could be argued correct.
4. **One repair:** a failed card got one rewrite from new sources and a fresh independent check, or it was cut.

## Cut cards
${dropped.map(d => `- ${d.id}: ${String(d.why).slice(0, 160)}`).join('\n') || '- none'}

## Passed cards
| id | score | stage | question | answer | sources |
|---|---|---|---|---|---|
${report.join('\n')}
`);

console.log(`kept ${kept.length}, dropped ${dropped.length}`, byDeck);
